def devkit_pin_number(gpio):
    """DevKitC socket pin number (1-38) that carries a GPIO."""
    names = DEVKITC['J2'] + DEVKITC['J3']
    return names.index('IO%d' % gpio) + 1


def _devkit_pins():
    pins = {}
    names = DEVKITC['J2'] + DEVKITC['J3']
    for i, name in enumerate(names):
        num = str(i + 1)
        if name == '3V3':
            pins[num] = '+3V3'
        elif name == '5V':
            pins[num] = 'DEVKIT_5V'
        elif name == 'GND':
            pins[num] = 'GND'
        elif name.startswith('IO') and int(name[2:]) in GPIO_NETS:
            pins[num] = GPIO_NETS[int(name[2:])][0]
    return pins


