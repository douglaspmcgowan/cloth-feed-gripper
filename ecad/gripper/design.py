def nets():
    """net -> sorted [(ref, pin)] from PARTS, virtual parts (power flags) excluded."""
    out = {}
    for p in PARTS:
        if p.get('virtual'):
            continue
        for pin, net in p['pins'].items():
            out.setdefault(net, []).append((p['ref'], pin))
    return {k: sorted(v) for k, v in out.items()}


def bom_parts():
    """Parts that are bought and placed (no power flags, no mounting holes)."""
    return [p for p in PARTS if not p.get('virtual') and p.get('bom', True)]
