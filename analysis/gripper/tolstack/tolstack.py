"""tolstack: tolerance stack-up CLI (worst case, RSS, Monte Carlo) for the ME102B gripper.

Run from the repository root (Python 3.13 with numpy, PyYAML, matplotlib). One command regenerates every
stack result, results/SUMMARY.md, results/summary.json, results/run_stdout.txt, the histograms in
results/figures/ and the generated tables in docs/gripper/analysis/tolerance_stacks.md:

  python analysis/gripper/tolstack/tolstack.py run
  python analysis/gripper/tolstack/tolstack.py revb      # every CAD rev B change at once, plus hot and 20.5 mm servo cases
  python analysis/gripper/tolstack/tolstack.py sens      # each assumed process input at 0.5x and 2x: verdict changes

  ... tolstack.py run my_stack.yaml --out /tmp/x --no-doc --set hole_cad_d=3.6   # try a change elsewhere
  ... tolstack.py sweep analysis/gripper/tolstack/stacks --stack T02 \
          --param recess_d_cad --values 19.40:19.60:0.01             # Cpk vs one constant
          (sweep a base stack: a variant's own set: wins over the swept constant)
  ... tolstack.py gdt position 0.2                               # GD&T -> +/- helper
  ... tolstack.py gdt perpendicularity 0.1 --length 10 --lever 85
  ... tolstack.py fastener fixed --H 3.25 --F 2.98 --T2 0.05     # ASME fastener formulas (H = hole MMC)

YAML format: see analysis/gripper/tolstack/stacks/*.yaml and docs/gripper/analysis/tolerance_stacks.md.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tolcalc import gdt as G  # noqa: E402
from tolcalc import report, run_all, scenarios  # noqa: E402
from tolcalc.model import load_stacks  # noqa: E402


def _kv(items):
    out = {}
    for it in items or []:
        k, v = it.split("=", 1)
        try:
            out[k] = float(v)
        except ValueError:
            out[k] = v
    return out


HERE = Path(__file__).resolve().parent
DEFAULT_STACKS = HERE / "stacks"
DEFAULT_OUT = HERE / "results"
DEFAULT_DOC = HERE.parents[2] / "docs" / "gripper" / "analysis" / "tolerance_stacks.md"
MIN_SAMPLES = 20_000


def cmd_run(a):
    if a.samples < MIN_SAMPLES:
        raise SystemExit(f"tolstack run: --samples {a.samples} is below the {MIN_SAMPLES:,} floor")
    paths = a.paths or [str(DEFAULT_STACKS)]
    results = run_all(paths, n=a.samples, seed=a.seed, const_overrides=_kv(a.set))
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    fig_dir = Path(a.fig_dir) if a.fig_dir else out / "figures"
    for r in results:
        fig = fig_dir / f"tol_{r['id']}.png"
        if a.plots:
            report.histogram(r, fig)
        rel = os.path.relpath(fig, out).replace("\\", "/") if fig.exists() else None
        report.write_generated_text(out / f"{r['id']}.md", report.stack_markdown(r, rel))
        clean = {k: v for k, v in r.items() if not k.startswith("_")}
        report.write_generated_text(out / f"{r['id']}.json", report.dumps(
            report.attach_input_digest(clean, HERE)))
    table = "\n".join(report.summary_rows(results))
    verdicts = "\n".join(report.verdict_rows(results))
    options = "\n".join(report.option_rows(results))
    head = (f"N = {a.samples:,} Monte Carlo samples per stack, seed {a.seed}. Verdict: PASS at Cpk ≥ 1.33 "
            "(MC-accepted) or worst case inside spec (WC-accepted); MARGINAL at 1.0 ≤ Cpk < 1.33, or a "
            "WC-accepted stack whose worst case breaks the spec while Cpk ≥ 1.0; FAIL otherwise.\n\n")
    head += f"Baseline (CAD rev A as drawn): {report.count_line(results)}.\n\n"
    summary_text = ("# Tolerance stack summary (generated by tolstack.py; do not hand-edit)\n\n" + head
        + "## Verdicts, CAD rev A baseline\n\n" + verdicts + "\n\n## Options, rejected layouts and scenarios\n\n"
        + options + "\n\n## All numbers\n\n" + table + "\n")
    report.write_generated_text(out / "SUMMARY.md", summary_text)
    keys = ("id", "title", "role", "variant_of", "companion_of", "nominal", "wc", "rss_classic", "rss_dist",
            "spec", "units", "method", "verdict", "verdict3", "own_verdict3", "yield_pct", "dominant", "fix",
            "fix_variant", "pass", "own_verdict", "blocked_by", "rss_clipped", "rss_nonlinear", "warnings",
            "verdict_band", "verdict_decided", "sampling_runs")
    summary_payload = {"samples": a.samples, "seed": a.seed, "overrides": _kv(a.set),
                       "generated_blocks": {"verdicts": verdicts, "options": options,
                                            "summary": table},
                       "generated_summary": summary_text,
                       "stacks": [{k: r[k] for k in keys if k in r} | {"mc": r["mc"]}
                                  for r in results]}
    report.write_generated_text(out / "summary.json", report.dumps(
        report.attach_input_digest(summary_payload, HERE)))
    if a.doc and not a.no_doc:
        report.update_doc(Path(a.doc), {"verdicts": verdicts, "options": options, "summary": table})
    text = "## Verdicts\n" + verdicts + "\n\n## Options\n" + options + "\n"
    warn = [f"WARNING {r['id']}: {w}" for r in results for w in r["warnings"]]
    report.write_generated_text(out / "run_stdout.txt", head + text + "\n".join(warn) + ("\n" if warn else ""))
    print(head + text)
    for w in warn:
        print(w, file=sys.stderr)
    return 0


def _values(spec):
    if ":" in spec:
        lo, hi, step = (float(x) for x in spec.split(":"))
        k = int(round((hi - lo) / step))
        return [round(lo + i * step, 10) for i in range(k + 1)]
    return [float(x) for x in spec.split(",")]


def cmd_sweep(a):
    base = _kv(a.set)
    rows = ["| " + a.param + " | Nominal | WC | MC 99.73 % band | Out % | Cpk | Verdict |",
            "|---:|---:|---|---|---:|---:|---|"]
    best = None
    points = []
    for v in _values(a.values):
        found = run_all(a.paths, n=a.samples, seed=a.seed, const_overrides={**base, a.param: v}, only={a.stack})
        if not found:
            raise SystemExit(f"tolstack sweep: stack id {a.stack!r} not found in {' '.join(a.paths)} "
                             "(ids are the YAML `id`, variants are <id>-<variant id>, e.g. T02-cad1951)")
        r = found[0]
        mc = r["mc"]
        cpk = mc["cpk_percentile"]
        if cpk is not None and (best is None or cpk > best[1]):
            best = (v, cpk)
        rows.append(f"| {v:g} | {report.f3(r['nominal'])} | {report.rng_str(r['wc'])} | "
                    f"{report.f3(mc['p0135'])} … {report.f3(mc['p99865'])} | {mc['out_pct']:.3g} | "
                    f"{report.f3(cpk, 2)} | {report.v3_str(r)} |")
        points.append({a.param: v, "nominal": r["nominal"], "wc": r["wc"], "out_pct": mc["out_pct"],
                       "cpk": cpk, "verdict3": r["verdict3"]})
    first = {lvl: next((p[a.param] for p in points if p["verdict3"] in ok), None)
             for lvl, ok in (("marginal_or_better", ("marginal", "pass")), ("pass", ("pass",)))}
    text = (f"# Sweep of {a.param} on {a.stack} (generated by tolstack.py sweep)\n\n"
            f"N = {a.samples:,}, seed {a.seed}. Best Cpk {best[1]:.2f} at {a.param} = {best[0]:g}. "
            f"First MARGINAL-or-better at {a.param} = {first['marginal_or_better']}; "
            f"first PASS at {first['pass']}.\n\n"
            + "\n".join(rows) + "\n")
    if a.out:
        out = Path(a.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        report.write_generated_text(out, text)
        paths = [Path(p).resolve() for p in a.paths]
        payload = {"stack": a.stack, "param": a.param, "samples": a.samples, "seed": a.seed,
                   "paths": [os.path.relpath(p, HERE).replace("\\", "/") for p in paths],
                   "values": a.values, "overrides": base, "first": first, "points": points}
        report.write_generated_text(out.with_suffix(".json"), report.dumps(
            report.attach_input_digest(payload, HERE)))
    print(text)
    return 0


def _rev_b_inputs(a):
    return DEFAULT_STACKS, scenarios.load_overlay(DEFAULT_STACKS / "rev_b.yaml")


def cmd_revb(a):
    """Rerun every stack with all CAD rev B changes applied together; write results/rev_b/."""
    stacks, ov = _rev_b_inputs(a)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    names = a.case or list(ov["cases"])
    runs = {c: scenarios.run_case(stacks, ov, c, a.samples, a.seed) for c in names}
    ref = (runs.get("drawn") or scenarios.run_case(stacks, ov, "drawn", a.samples, a.seed))[0]
    L = ["# CAD rev B combined run (generated by tolstack.py revb; do not hand-edit)", "",
         f"N = {a.samples:,} Monte Carlo samples per stack, seed {a.seed}. Every rev B change is applied at once "
         "(`stacks/rev_b.yaml`: constants plus the picked variants), so the set is judged together, not one fix at a time. "
         "Verdict rule as in SUMMARY.md.", ""]
    doc = []
    for c in names:
        if c == "drawn":
            continue
        res, also = runs[c]
        t = scenarios.tally(res)
        drawn_like = not ov["cases"][c].get("base", True)
        main = ref if drawn_like else (None if c == "revb" else runs["revb"][0] if "revb" in runs else None)
        head = f"**{ov['cases'][c]['label']}** (`{c}`). " + scenarios.tally_line(t)
        if main is not None:
            head += f" Only the checks that differ from the {'rev A as drawn' if drawn_like else '`revb`'} run are listed."
        tab = scenarios.case_table(res, ref, also, main)
        if main is not None and len(tab) == 2:
            tab = ["Every check is identical to that run."]
        L += [f"## {c}", "", head, ""] + tab + [""]
        doc += [head, ""] + tab + [""]
        payload = {"case": c, "label": ov["cases"][c]["label"], "tally": t,
                   "stacks": [scenarios.trim(r) for r in res],
                   "alternatives": [scenarios.trim(r) for r in also]}
        report.write_generated_text(out / f"{c}.json", report.dumps(
            report.attach_input_digest(payload, HERE)))
    t0 = scenarios.tally(ref)
    L += ["## Reference: rev A as drawn", "", scenarios.tally_line(t0), ""]
    release = report.release_gate(out / "revb.json", out / "revb_hot.json", stacks)
    L += ["## Release gate", "", release, ""]
    report.write_generated_text(out / "REVB.md", "\n".join(L).rstrip("\n") + "\n")
    combined = "\n".join(doc).rstrip()
    revb_path = out / "revb.json"
    revb_payload = json.loads(revb_path.read_text(encoding="utf-8"))
    revb_payload["generated_blocks"] = {"release": release, "revb": combined}
    report.write_generated_text(revb_path, report.dumps(
        report.attach_input_digest(revb_payload, HERE)))
    if a.doc and not a.no_doc:
        report.update_doc(Path(a.doc), {"release": release, "revb": combined})
    print("\n".join(L))
    return 0


def cmd_sens(a):
    """Rerun every stack with each assumed process input at 0.5x and 2x; list the verdict changes."""
    stacks, ov = _rev_b_inputs(a)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    data = scenarios.run_sens(stacks, ov, a.samples, a.seed, progress=(lambda m: print("sens", m, file=sys.stderr)))
    L = ["# Sensitivity to the assumed process inputs (generated by tolstack.py sens; do not hand-edit)", "",
         f"N = {a.samples:,} per stack, seed {a.seed}. Each input is multiplied by every factor in "
         f"{', '.join(f'{x:g}x' for x in data['scales'])} with all else unchanged; only changed verdicts are listed.", ""]
    body = scenarios.sens_tables(data)
    report.write_generated_text(out / "SENS.md", "\n".join(L + body).rstrip("\n") + "\n")
    data["generated_blocks"] = {"sens": "\n".join(body).rstrip()}
    report.write_generated_text(out / "sens.json", report.dumps(report.attach_input_digest(data, HERE)))
    if a.doc and not a.no_doc:
        report.update_doc(Path(a.doc), {"sens": "\n".join(body).rstrip()})
    print("\n".join(L + body))
    return 0


def cmd_gdt(a):
    g = {"type": a.type, "zone": a.zone}
    for k in ("bonus", "length", "lever", "outer"):
        if getattr(a, k) is not None:
            g[k] = getattr(a, k)
    up, lo = G.convert(g)
    print(json.dumps({"gdt": g, "upper": up, "lower": lo}))
    return 0


def cmd_fastener(a):
    if a.kind == "floating":
        res = {"T_each_part_dia": G.floating_fastener_T(a.H, a.F), "H_check": G.floating_fastener_H(a.F, a.H - a.F)}
    else:
        tot = G.fixed_fastener_total(a.H, a.F)
        t2 = a.T2 if a.T2 is not None else tot / 2
        res = {"T1_plus_T2_dia": tot, "T2_threaded_part": t2, "T1_clearance_part": tot - t2}
    print(json.dumps({"kind": a.kind, "H": a.H, "F": a.F, **res}))
    return 0


def _fingerprint_rows(overrides=None):
    rows = {}
    for path in sorted(DEFAULT_STACKS.glob("*.yaml"), key=lambda item: item.name.lower()):
        for stack in load_stacks(path, overrides):
            rows[stack.id] = sorted(({
                "name": item.name,
                "sign": -1 if item.a < 0 else 1,
                "sensitivity": item.a,
                "distribution": item.dist,
                "tolerance": item.upper - item.lower,
            } for item in stack.contributors), key=lambda item: item["name"])
    return rows


def cmd_fingerprints(a):
    overlay = scenarios.load_overlay(DEFAULT_STACKS / "rev_b.yaml")
    payload = {"revision_a": _fingerprint_rows(), "revision_b": _fingerprint_rows(overlay["rev_b"]["set"])}
    report.write_generated_text(Path(a.out), json.dumps(payload, indent=2, sort_keys=True) + "\n")
    print(f"wrote {a.out}: {len(payload['revision_a'])} stack variants")
    return 0


def cmd_check() -> int:
    """Compare generated text and provenance without sampling or writing."""
    errors, count, results = report.check_generated(DEFAULT_OUT, DEFAULT_DOC, HERE)
    if errors:
        print(errors[0], file=sys.stderr)
        return 1
    paths = [path for path in DEFAULT_OUT.rglob("*.json") if "_superseded" not in path.parts]
    print(f"generated output current: {count} blocks, {len(paths)} files, {results} verdicts checked")
    return 0


def main(argv=None):
    for s in (sys.stdout, sys.stderr):  # Windows consoles default to cp1252; the tables use ≥, Ø, …
        if hasattr(s, "reconfigure"):
            s.reconfigure(encoding="utf-8")
    argv = sys.argv[1:] if argv is None else argv
    if argv == ["--check"]:
        return cmd_check()
    p = argparse.ArgumentParser(prog="tolstack", description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    fp = sub.add_parser("fingerprints", help="write resolved contributor fingerprints")
    fp.add_argument("--out", default=str(HERE / "tests" / "loop_fingerprints.json"))
    fp.set_defaults(func=cmd_fingerprints)
    r = sub.add_parser("run", help="analyse YAML stacks (files or directories; default: every stack)")
    r.add_argument("paths", nargs="*")
    r.add_argument("--out", default=str(DEFAULT_OUT))
    r.add_argument("--fig-dir", default=None, help="histogram PNGs (default: <out>/figures)")
    r.add_argument("--doc", default=str(DEFAULT_DOC),
                   help="markdown file with tolstack:verdicts/options/summary markers to refresh")
    r.add_argument("--no-doc", action="store_true", help="do not touch the markdown doc")
    r.add_argument("--samples", type=int, default=100_000)
    r.add_argument("--seed", type=int, default=20260922)
    r.add_argument("--set", action="append", help="override a constant, name=value")
    r.add_argument("--plots", action="store_true",
                   help="redraw the histogram PNGs (off by default: PNG bytes differ between matplotlib builds, "
                        "so a plain rerun must not touch the committed figures)")
    r.set_defaults(func=cmd_run)
    for name, fn, hlp in (("revb", cmd_revb, "all CAD rev B changes at once, plus hot-seat and 20.5 mm servo cases"),
                          ("sens", cmd_sens, "each assumed process input at 0.5x and 2x: verdict changes")):
        q = sub.add_parser(name, help=hlp)
        q.add_argument("--out", default=str(DEFAULT_OUT / ("rev_b" if name == "revb" else "sens")))
        q.add_argument("--doc", default=str(DEFAULT_DOC))
        q.add_argument("--no-doc", action="store_true", help="do not touch the markdown doc")
        q.add_argument("--samples", type=int, default=100_000)
        q.add_argument("--seed", type=int, default=20260922)
        if name == "revb":
            q.add_argument("--case", action="append", help="only this case from stacks/rev_b.yaml (repeatable)")
        q.set_defaults(func=fn)
    w = sub.add_parser("sweep", help="rerun one stack over a range of one basis constant")
    w.add_argument("paths", nargs="+")
    w.add_argument("--stack", required=True, help="stack id (variants allowed, e.g. T02-cad1951)")
    w.add_argument("--param", required=True)
    w.add_argument("--values", required=True, help="lo:hi:step or a,b,c")
    w.add_argument("--samples", type=int, default=100_000)
    w.add_argument("--seed", type=int, default=20260922)
    w.add_argument("--set", action="append", help="extra override, name=value")
    w.add_argument("--out", default=None, help="write the markdown table here")
    w.set_defaults(func=cmd_sweep)
    g = sub.add_parser("gdt", help="convert a GD&T callout to +/-")
    g.add_argument("type")
    g.add_argument("zone", type=float)
    for k in ("bonus", "length", "lever", "outer"):
        g.add_argument(f"--{k}", type=float)
    g.set_defaults(func=cmd_gdt)
    f = sub.add_parser("fastener", help="ASME floating / fixed fastener formulas")
    f.add_argument("kind", choices=["floating", "fixed"])
    f.add_argument("--H", type=float, required=True, help="hole MMC dia")
    f.add_argument("--F", type=float, required=True, help="fastener MMC dia")
    f.add_argument("--T2", type=float, help="fixed: tolerance taken by the threaded part")
    f.set_defaults(func=cmd_fastener)
    a = p.parse_args(argv)
    return a.func(a)


if __name__ == "__main__":
    raise SystemExit(main())
